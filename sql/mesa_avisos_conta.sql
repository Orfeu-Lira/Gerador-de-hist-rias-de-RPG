CREATE TABLE IF NOT EXISTS public.mesa_avisos_conta (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id bigint NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
 auditoria_id bigint UNIQUE,
 tipo text NOT NULL CHECK(tipo IN ('ia_concedida','ia_revogada')),
 criado_em timestamptz NOT NULL DEFAULT now(), lido_em timestamptz
);
ALTER TABLE public.mesa_avisos_conta ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.mesa_avisos_conta FROM anon,authenticated;
CREATE INDEX IF NOT EXISTS mesa_avisos_conta_usuario ON public.mesa_avisos_conta(usuario_id,id DESC);
INSERT INTO public.mesa_avisos_conta(usuario_id,auditoria_id,tipo,criado_em)
SELECT u.id,a.id,'ia_concedida',a.criado_em FROM public.usuarios u
JOIN LATERAL (SELECT id,criado_em,detalhes FROM public.mesa_auditoria WHERE alvo_tipo='usuario' AND alvo_id=u.id AND acao='usuario.privilegio_ia' ORDER BY id DESC LIMIT 1) a ON true
WHERE u.ia_ilimitada AND u.papel<>'admin' AND a.detalhes->>'iaIlimitada'='true'
ON CONFLICT(auditoria_id) DO NOTHING;
