-- Mesa RPG Solo v1: campaigns are account-owned; no client-side direct table access.
CREATE TABLE IF NOT EXISTS public.mesa_solo_campanhas (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id bigint NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
 aventura_id bigint REFERENCES public.aventuras(id) ON DELETE SET NULL,
 titulo varchar(140) NOT NULL,
 genero varchar(70) NOT NULL,
 tom varchar(60) NOT NULL,
 premissa text NOT NULL,
 resumo text NOT NULL DEFAULT '',
 turno_atual integer NOT NULL DEFAULT 0,
 processando boolean NOT NULL DEFAULT false,
 criado_em timestamptz NOT NULL DEFAULT now(),
 atualizado_em timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT solo_turnos_validos CHECK (turno_atual>=0),
 CONSTRAINT solo_premissa_limite CHECK (char_length(premissa)<=6000),
 CONSTRAINT solo_resumo_limite CHECK (char_length(resumo)<=4000)
);
CREATE TABLE IF NOT EXISTS public.mesa_solo_mensagens (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 campanha_id bigint NOT NULL REFERENCES public.mesa_solo_campanhas(id) ON DELETE CASCADE,
 numero integer NOT NULL,
 papel varchar(12) NOT NULL CHECK (papel IN ('jogador','mestre')),
 tipo varchar(12) NOT NULL DEFAULT 'acao' CHECK (tipo IN ('acao','ajuste','inicio')),
 texto text NOT NULL,
 criado_em timestamptz NOT NULL DEFAULT now(),
 UNIQUE(campanha_id,numero,papel),
 CONSTRAINT solo_mensagem_tamanho CHECK (char_length(texto)>0 AND char_length(texto)<=5000)
);
CREATE INDEX IF NOT EXISTS mesa_solo_campanhas_usuario ON public.mesa_solo_campanhas(usuario_id,atualizado_em DESC);
CREATE INDEX IF NOT EXISTS mesa_solo_mensagens_campanha ON public.mesa_solo_mensagens(campanha_id,numero DESC);
ALTER TABLE public.mesa_solo_campanhas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.mesa_solo_mensagens ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.mesa_solo_campanhas,public.mesa_solo_mensagens FROM anon,authenticated;
REVOKE ALL ON SEQUENCE public.mesa_solo_campanhas_id_seq,public.mesa_solo_mensagens_id_seq FROM anon,authenticated;
