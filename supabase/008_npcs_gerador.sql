-- Gerador de NPCs independente, pertencente ao usuário do Mesa.
CREATE TABLE IF NOT EXISTS public.mesa_npcs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id bigint NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
 aventura_id bigint REFERENCES public.aventuras(id) ON DELETE SET NULL,
 conteudo jsonb NOT NULL,
 criado_em timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT mesa_npc_conteudo_objeto CHECK (jsonb_typeof(conteudo)='object')
);
CREATE INDEX IF NOT EXISTS mesa_npcs_usuario_criado ON public.mesa_npcs(usuario_id,criado_em DESC);
ALTER TABLE public.mesa_npcs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.mesa_npcs FROM anon,authenticated;
REVOKE ALL ON SEQUENCE public.mesa_npcs_id_seq FROM anon,authenticated;
